<script>
    // Handle Application Modal Logic
    document.addEventListener('DOMContentLoaded', () => {
        const modal = document.getElementById('apply-modal');
        const positionSelect = document.getElementById('position');
        const applyLinks = document.querySelectorAll('a[href="#apply-form"]');

        // Check if there is a status message in URL (meaning form was submitted)
        const urlParams = new URLSearchParams(window.location.search);
        if (urlParams.has('status')) {
            modal.classList.remove('hidden');
            document.body.style.overflow = 'hidden';
            
            // Clean URL by removing the query params so it doesn't pop up again on refresh
            const newUrl = window.location.protocol + "//" + window.location.host + window.location.pathname;
            window.history.pushState({path:newUrl}, '', newUrl);
        }

        applyLinks.forEach(link => {
            link.addEventListener('click', (e) => {
                e.preventDefault();
                // Extract Job Title from the specific card that was clicked
                const jobTitle = link.querySelector('h3').innerText;
                
                // Set the dropdown to match the Job Title
                if (positionSelect) {
                    // Try to find matching option
                    let optionFound = false;
                    Array.from(positionSelect.options).forEach(opt => {
                        if (opt.value === jobTitle) {
                            positionSelect.value = jobTitle;
                            optionFound = true;
                        }
                    });
                    if (!optionFound) positionSelect.value = 'Other';
                }

                // Show modal & prevent body scroll
                modal.classList.remove('hidden');
                document.body.style.overflow = 'hidden';
            });
        });
        
        // Close modal when clicking outside the box
        modal.addEventListener('click', (e) => {
            if (e.target === modal) {
                closeApplyModal();
            }
        });
    });

    function closeApplyModal() {
        const modal = document.getElementById('apply-modal');
        modal.classList.add('hidden');
        document.body.style.overflow = '';
    }
</script>

