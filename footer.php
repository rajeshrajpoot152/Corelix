        // Sticky Stack Cards Scroll Effect
        document.addEventListener('DOMContentLoaded', () => {
            const stackCards = document.querySelectorAll('#products article');
            if (stackCards.length === 0) return;

            window.addEventListener('scroll', () => {
                if (window.innerWidth < 900) {
                    stackCards.forEach(c => { 
                        c.style.transform = ''; 
                        c.style.opacity = ''; 
                    });
                    return;
                }
                
                stackCards.forEach((card, index) => {
                    const rect = card.getBoundingClientRect();
                    const stickyTop = parseInt(window.getComputedStyle(card).top);
                    
                    // If card is at or above its sticky point
                    if (rect.top <= stickyTop + 1) {
                        let stackedOnTop = 0;
                        
                        // Calculate how many subsequent cards have scrolled over this one
                        for (let j = index + 1; j < stackCards.length; j++) {
                            const nextRect = stackCards[j].getBoundingClientRect();
                            const nextStickyTop = parseInt(window.getComputedStyle(stackCards[j]).top);
                            
                            let progress = 1 - ((nextRect.top - nextStickyTop) / (window.innerHeight * 0.7));
                            progress = Math.max(0, Math.min(1, progress));
                            stackedOnTop += progress;
                        }
                        
                        // Apply scaling and fading based on how many cards are stacked on top
                        const scale = Math.max(0.85, 1 - (stackedOnTop * 0.04));
                        const opacity = Math.max(0.3, 1 - (stackedOnTop * 0.25));
                        
                        card.style.transform = `scale(${scale})`;
                        card.style.opacity = opacity;
                        card.style.transformOrigin = 'center top';
                    } else {
                        // Reset if not stuck
                        card.style.transform = `scale(1)`;
                        card.style.opacity = `1`;
                    }
                });
            });
        });
