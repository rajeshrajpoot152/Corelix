    <script>
        function openGlobalInquiryModal(e) {
            if(e) e.preventDefault();
            const modal = document.getElementById("global-inquiry-modal");
            const content = document.getElementById("inquiry-modal-content");
            if (modal) {
                modal.classList.remove("hidden");
                // Trigger fade in animation
                setTimeout(() => {
                    modal.classList.remove("opacity-0");
                    if(content) content.classList.remove("scale-95");
                }, 50);
            }
        }

        function closeGlobalInquiryModal() {
            const modal = document.getElementById("global-inquiry-modal");
            const content = document.getElementById("inquiry-modal-content");
            if (modal) {
                modal.classList.add("opacity-0");
                if(content) content.classList.add("scale-95");
                setTimeout(() => {
                    modal.classList.add("hidden");
                }, 300);
            }
        }
        
        // Allow closing by clicking outside
        document.addEventListener('DOMContentLoaded', () => {
            const globalModal = document.getElementById('global-inquiry-modal');
            if (globalModal) {
                globalModal.addEventListener('click', (e) => {
                    if (e.target === globalModal) {
                        closeGlobalInquiryModal();
                    }
                });
            }
        });
    </script>
